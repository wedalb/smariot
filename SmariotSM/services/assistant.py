def extract_prompt(transcribed_text, wake_word):
    """
    Extracts the user's prompt from the transcribed text, removing the wake word and any leading punctuation.

    This function uses a regular expression to search for the wake word in the transcribed text and extract
    the prompt that follows it.

    Parameters:
    transcribed_text (str): The text transcribed from the user's speech.
    wake_word (str): The wake word used to activate the voice assistant.

    Returns:
    str or None: The extracted prompt text if the wake word is found, otherwise None.

    Example:
    prompt = extract_prompt("Hey smariot, what's the weather today?", "Hey smariot")
    logger.info(prompt)  # Output: "what's the weather today?"

    Notes:
    - The `re` module must be imported for regular expression operations.
    - The function assumes that the wake word is a distinct word or phrase used to trigger the voice assistant.
    - The regular expression pattern accounts for optional whitespace and punctuation immediately following the wake word.
    """
    logger.debug("Extracting prompt from transcribed text: %s with wake word: %s", transcribed_text, wake_word)

    pattern = rf'\b{re.escape(wake_word)}[\s,.?!]*([A-Za-z0-9].*)'
    match = re.search(pattern, transcribed_text, re.IGNORECASE)

    if match:
        prompt = match.group(1).strip()
        logger.info("Extracted prompt: %s", prompt)
        return prompt
    else:
        logger.info("Wake word not found in transcribed text")
        return None
def speak(text):
    """
    Converts the given text into speech and plays it through the audio output device.

    This function uses the OpenAI client to generate speech from text, and plays the resulting audio in real-time using PyAudio.

    Parameters:
    text (str): The text to be converted into speech.

    Returns:
    None

    Example:
    speak("Hello, how can I assist you today?")
    # This will convert the text into speech and play it through the audio output device.

    Notes:
    - The `pyaudio` module must be imported and configured correctly for audio playback.
    - The `openai_client` must be defined and configured to access the OpenAI API for text-to-speech conversion.
    - The function uses the 'tts-1' model and 'echo' voice for speech synthesis.
    - The `response_format` is set to 'pcm' and the audio is streamed in chunks of 1024 bytes.
    - The function starts playing audio when it detects a non-silence chunk, determined by the `silence_threshold`.
    """
    try:
        logger.debug("Opening PyAudio stream")
        player_stream = pyaudio.PyAudio().open(format=pyaudio.paInt16, channels=1, rate=24000, output=True)
        stream_start = False

        logger.debug("Generating speech for text: %s", text)
        with openai_client.audio.speech.with_streaming_response.create(
            model='tts-1',
            voice='echo',
            response_format='pcm',
            input=text,
        ) as response:
            silence_threshold = 0.01
            for chunk in response.iter_bytes(chunk_size=1024):
                if stream_start:
                    player_stream.write(chunk)
                else:
                    if max(chunk) > silence_threshold:
                        player_stream.write(chunk)
                        stream_start = True
        logger.info("Speech playback completed")
    except Exception as e:
        logger.error("An error occurred during speech synthesis or playback: %s", e)
