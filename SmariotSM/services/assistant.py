def fetch_nearby_senior_centers(lat, lon, keyword='Seniorentreff'):
    """
    Fetches and returns a list of nearby senior centers based on the given latitude and longitude.

    Parameters:
    lat (float): The latitude of the location to search around.
    lon (float): The longitude of the location to search around.
    keyword (str): Optional. The keyword to search for. Defaults to 'Seniorentreff'.

    Returns:
    list: A list of dictionaries, each containing information about a nearby senior center.
          Each dictionary includes the following keys:
          - 'name': The name of the place.
          - 'address': The address of the place.
          - 'rating': The rating of the place.
          - 'types': A list of types associated with the place.
          If the request fails, returns an empty list.

    Example:
    senior_centers = fetch_nearby_senior_centers(52.5200, 13.4050)
    for center in senior_centers:
        logger.info(f"Name: {center['name']}, Address: {center['address']}, Rating: {center['rating']}")

    Notes:
    - The `requests` module must be imported for making HTTP requests.
    - The `GOOGLE_PLACES_API_KEY` must be defined and contain a valid API key for the Google Places API.
    - This function sends a GET request to the Google Places API to search for nearby places within a 5 km radius using the specified keyword.
    - If the request is successful, the function returns a list of places with their name, address, rating, and types.
    - If the request fails, the function logs an error message with the status code and returns an empty list.
    """
    logger.debug("Fetching nearby senior centers for coordinates: (%f, %f) with keyword: %s", lat, lon, keyword)

    url = 'https://maps.googleapis.com/maps/api/place/nearbysearch/json'
    params = {
        'location': f'{lat},{lon}',
        'radius': 5000,  # Search within 5 km
        'keyword': keyword,
        'key': GOOGLE_PLACES_API_KEY
    }

    try:
        response = requests.get(url, params=params)
        response.raise_for_status()  # Raises an HTTPError for bad responses
        results = response.json().get('results', [])
        places = []
        for place in results:
            place_info = {
                'name': place['name'],
                'address': place.get('vicinity', 'No address provided'),
                'rating': place.get('rating', 'No rating provided'),
                'types': place.get('types', [])
            }
            places.append(place_info)
        logger.info("Successfully fetched %d senior centers", len(places))
        return places
    except requests.exceptions.HTTPError as e:
        logger.error("HTTP error occurred: %s", e)
    except requests.exceptions.RequestException as e:
        logger.error("Request exception occurred: %s", e)
    except KeyError as e:
        logger.error("Key error occurred while processing the response: %s", e)
    except Exception as e:
        logger.error("An unexpected error occurred: %s", e)

    return []
