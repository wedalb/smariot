def groq_prompt(prompt, img_context):
    """
    Sends a user prompt and an optional image context to the Groq client for generating a chat completion.
    The function appends the prompt and the generated response to a conversation list and returns the content of the response.

    Parameters:
    prompt (str): The user input prompt that will be sent to the Groq client.
    img_context (str or None): Optional. Additional context related to an image. If provided, it will be included in the prompt sent to the Groq client.

    Returns:
    str: The content of the response generated by the Groq client.

    Example:
    response_content = groq_prompt("What is the weather today?", "A picture of a sunny beach")
    logger.info(response_content)

    Notes:
    - The `groq_client` and `convo` must be defined in the global scope or passed appropriately for the function to work correctly.
    - This function assumes that `groq_client.chat.completions.create` and the structure of the response are as specified.
    """
    if img_context:
        prompt = f'PROMPT: {prompt}\n\nBILD KONTEXT: {img_context}'
        logger.debug(f"Image context provided, updated prompt: {prompt}")
    else:
        logger.debug(f"No image context provided, using prompt: {prompt}")

    convo.append({'role': 'user', 'content': prompt})
    logger.debug(f"Appended user prompt to conversation: {convo}")

    try:
        chat_completion = groq_client.chat.completions.create(messages=convo, model='llama3-70b-8192')
        response = chat_completion.choices[0].message
        convo.append(response)
        logger.debug(f"Appended response to conversation: {response}")

        return response.content
    except Exception as e:
        logger.error(f"An error occurred while generating chat completion: {e}")
        return None
