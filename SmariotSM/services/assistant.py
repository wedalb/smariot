def start_listening():
    """
    Starts the voice assistant's listening mechanism and manages the system's wake state.

    This function initializes the voice assistant to listen for a wake word and starts a background thread
    for continuous listening. It also monitors the time since the last interaction and resets the system
    if there is no interaction for a specified duration.

    Parameters:
    None

    Returns:
    None

    Example:
    start_listening()
    # This will start the voice assistant listening for the wake word and reset the system if inactive for the specified duration.

    Notes:
    - The `source`, `r`, `wake_word`, `background_listen`, `system_awake`, and `last_interaction_time` must be defined and properly configured in the global scope.
    - The `threading` module must be imported for creating and managing the background listening thread.
    - The `time` module must be imported for handling the time-based reset mechanism.
    - The system resets if there is no interaction for 120 seconds (2 minutes) by default. This duration can be adjusted by modifying the time condition in the function.
    - Ensure the microphone source and speech recognition library are properly configured for the function to work correctly.
    """
    global system_awake, last_interaction_time

    with source as s:
        r.adjust_for_ambient_noise(s, duration=2)
    logger.info('Say %s to wake up the system.', wake_word)

    # Start the background thread for listening
    listening_thread = threading.Thread(target=background_listen)
    listening_thread.daemon = True
    listening_thread.start()
    logger.debug("Background listening thread started")

    while True:
        current_time = time.time()
        # Reset system if no interaction for 2 minutes (120 seconds)
        if current_time - last_interaction_time > 120:
            system_awake = False
            logger.debug("System reset due to inactivity")
        time.sleep(.5)
