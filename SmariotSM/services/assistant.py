def callback(recognizer, audio):
    """
    Handles audio input from the speech recognizer and processes it to activate and interact with the voice assistant.

    This function is a callback that processes audio input, recognizes speech using the Google Web Speech API in German,
    and handles the system's wake state and user prompts. It activates the system if the wake word is detected and processes
    user prompts accordingly.

    Parameters:
    recognizer (Recognizer): The speech recognizer instance that captured the audio.
    audio (AudioData): The audio data captured by the recognizer.

    Returns:
    None

    Example:
    r.listen_in_background(source, callback)
    # This sets up the recognizer to use the callback function for processing background audio.

    Notes:
    - The `recognizer` and `audio` parameters are provided by the speech recognition library's listening mechanism.
    - The `system_awake`, `last_interaction_time`, `wake_word`, `extract_prompt`, and `handle_prompt` must be defined and properly configured in the global scope.
    - The `speech_recognition` library must be imported as `sr` and configured correctly for the function to work.
    - This function attempts to recognize speech using the Google Web Speech API in German (language code 'de-DE').
    - If the system is not awake, it checks for the wake word in the recognized text to activate the system.
    - Once the system is awake, it processes the entire recognized text as the user prompt.
    - If the recognition fails, appropriate error messages are logged.
    """
    global system_awake, last_interaction_time

    try:
        # Recognize speech using Google Web Speech API in German
        prompt_text = recognizer.recognize_google(audio, language='de-DE')
        logger.info("Prompt: %s", prompt_text)

        if not system_awake:
            if wake_word.lower() in prompt_text.lower():
                system_awake = True
                last_interaction_time = time.time()
                logger.info("System is now awake. You can speak without the wake word.")

                clean_prompt = extract_prompt(prompt_text, wake_word) # Since system is not awake, use the clean prompt
                last_interaction_time = time.time()
                logger.debug("Clean prompt: %s", clean_prompt)

                handle_prompt(clean_prompt)
            else:
                logger.info("Please say the wake word to activate the system.")
        else:
            clean_prompt = prompt_text # Since system is awake, use the entire prompt
            last_interaction_time = time.time()
            logger.debug("Clean prompt: %s", clean_prompt)

            handle_prompt(clean_prompt)
    except sr.UnknownValueError:
        logger.error("Google Speech Recognition could not understand audio")
    except sr.RequestError as e:
        logger.error("Could not request results from Google Speech Recognition service; %s", e)
