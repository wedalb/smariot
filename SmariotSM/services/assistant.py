def get_current_time(location=DEFAULT_LOCATION):
    """
    Fetches and returns the current local time for a given location.

    Parameters:
    location (str): Optional. The location for which to fetch the current time. Defaults to `DEFAULT_LOCATION`.

    Returns:
    str: A string describing the current local time in the specified location, formatted as:
         "Aktuelle Uhrzeit in <location>: %Y-%m-%d %H:%M:%S"

    Example:
    current_time = get_current_time("Berlin")
    print(current_time)  # Output might be "Aktuelle Uhrzeit in Berlin: 2024-07-09 15:45:30"

    Notes:
    - The `pytz` module must be installed and imported for timezone handling.
    - The `datetime` module must be imported for fetching the current time.
    - The `location_mapping` dictionary maps known locations to their respective timezones. If a location is not found in the dictionary, the default timezone "Etc/UTC" is used.
    - The `DEFAULT_LOCATION` constant must be defined in the global scope or imported appropriately for the function to work correctly.
    """
    location_mapping = {
        "New York": "America/New_York",
        "Berlin": "Europe/Berlin",
        "Munich": "Europe/Berlin"
    }
    timezone = location_mapping.get(location, "Etc/UTC")
    logger.debug("Fetching time for location: %s, Timezone: %s", location, timezone)

    tz = pytz.timezone(timezone)
    current_time = datetime.now(tz)
    formatted_time = current_time.strftime(f"Aktuelle Uhrzeit in {location}: %Y-%m-%d %H:%M:%S")

    logger.info("Current time fetched for location %s: %s", location, formatted_time)
    return formatted_time
